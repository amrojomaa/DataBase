public void select() {
   try
    {
        DriverManager.registerDriver(new org.postgresql.Driver());
        String custr = "jdbc:postgresql://localhost:5432/postgres";
        String un = "amro";
        String up = "123456";
        Connection con = DriverManager.getConnection(custr, un, up);
        Statement stmt = con.createStatement();
        
        DefaultTableModel model = (DefaultTableModel) producttable.getModel();
        model.setRowCount(0);
        String query = "SELECT * FROM product order by productid"; // Query to select all columns
        ResultSet rs = stmt.executeQuery(query);

        while (rs.next()) {
            int ID = rs.getInt("productid");
            String Name = rs.getString("name");
            String Quantity = rs.getString("quantity");
            String Price = rs.getString("price");
             String Category = rs.getString("category");

            // Add a row to the table model
            model.addRow(new Object[]{ID, Name,Quantity,Price,Category});
        }  
    }catch(Exception ex)
    {
     JOptionPane.showMessageDialog(null, ex.toString());   
    } 
}





