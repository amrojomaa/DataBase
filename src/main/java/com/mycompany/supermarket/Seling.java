                Connection con = DriverManager.getConnection(custr, un, up);
                Statement st = con.createStatement();
                String query = "SELECT * FROM Product WHERE category='" + CatCb.getSelectedItem().toString() + "'order by productid";
                ResultSet rs = st.executeQuery(query);

                // Get metadata to determine the number of columns and column names
                ResultSetMetaData rsMeta = rs.getMetaData();
                int columnCount = rsMeta.getColumnCount();

                // Create the DefaultTableModel with column names
                DefaultTableModel model = new DefaultTableModel();
                for (int i = 1; i <= columnCount; i++) {
                    model.addColumn(rsMeta.getColumnName(i));
                }

                // Populate the table model with data from the ResultSet
                while (rs.next()) {
                    Object[] row = new Object[columnCount];
                    for (int i = 1; i <= columnCount; i++) {
                        row[i - 1] = rs.getObject(i);
                    }
                    model.addRow(row);
                }

                // Set the model for the producttable
                producttable.setModel(model);

