     public void select() {
   try
    {
        DriverManager.registerDriver(new org.postgresql.Driver());
        String custr = "jdbc:postgresql://localhost:5432/postgres";
        String un = "amro";
        String up = "123456";
        Connection con = DriverManager.getConnection(custr, un, up);
        Statement stmt = con.createStatement();
        
        DefaultTableModel model = (DefaultTableModel) sellertable.getModel();
        model.setRowCount(0);
        String query = "SELECT * FROM seller order by sellerid"; // Query to select all columns
        ResultSet rs = stmt.executeQuery(query);

        while (rs.next()) {
            int ID = rs.getInt("sellerid");
            String Name = rs.getString("name");
            String Pass = rs.getString("password");
            String Gender = rs.getString("gender");
           

            // Add a row to the table model
            model.addRow(new Object[]{ID, Name,Pass,Gender});
        }  
    }catch(Exception ex)
    {
     JOptionPane.showMessageDialog(null, ex.toString());   
    } 
}
    
