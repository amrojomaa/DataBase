    private void editsellMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_editsellMouseClicked
       if (sellid.getText().isEmpty() || sellername.getText().isEmpty() || sellerpassword.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Missing Information");
} else {
    try {
        DriverManager.registerDriver(new org.postgresql.Driver());
        String custr = "jdbc:postgresql://localhost:5432/postgres";
        String un = "amro";
        String up = "123456";
        Connection con = DriverManager.getConnection(custr, un, up);
        con.setAutoCommit(false);
        Statement stmt = con.createStatement();
        
        String sellid = this.sellid.getText();
        String sellername = this.sellername.getText();
        String sellerpassword = this.sellerpassword.getText();
        String gender = this.gender.getSelectedItem().toString();
        
        // SQL statement for updating category
        String strstmt = "UPDATE Seller SET name = '" + sellername + "', password = " + sellerpassword +",gender = '" + gender + "' WHERE sellerid = " + sellid;
        
        int rowsUpdated = stmt.executeUpdate(strstmt);
        
        if (rowsUpdated > 0) {
            con.commit();
            JOptionPane.showMessageDialog(this, "Seller Updated Successfully");
            select();
        } else {
            JOptionPane.showMessageDialog(this, "Seller ID not found");
        }
        
        con.close();
        
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(null, ex.toString());
    }
}
    }//GEN-LAST:event_editsellMouseClicked

